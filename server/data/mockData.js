/* ═══════════════════════════════════════════════════════════════
   SUMMARY STATISTICS
══════════════════════════════════════════════════════════════════ */

export function computeSummary() {
  const activeIncidents   = incidents.filter(i => i.status === "active");
  const totalAffected     = incidents.reduce((s, i) => s + i.affectedPeople, 0);
  const totalDisplaced    = incidents.reduce((s, i) => s + i.displaced,       0);
  const totalInjured      = incidents.filter(i => i.status !== "resolved").reduce((s, i) => s + i.injured, 0);
  const totalDeceased     = incidents.reduce((s, i) => s + i.deceased, 0);
  const criticalIncidents = incidents.filter(i => i.severity === "critical" && i.status === "active");

  const openShelters      = shelters.filter(s => s.status === "open");
  const totalShelterCap   = shelters.reduce((s, sh) => s + sh.totalCapacity,    0);
  const totalShelterOcc   = shelters.reduce((s, sh) => s + sh.currentOccupancy, 0);

  const criticalHospitals = hospitals.filter(h => h.operationalLoad >= 90);
  const totalFreeBeds     = hospitals.reduce((s, h) => s + h.freeBeds, 0);

  const activeAmbulances  = ambulanceTeams.filter(a => ["dispatched","on-scene","transporting","airborne"].includes(a.status));

  return {
    incidents: {
      total: incidents.length,
      active: activeIncidents.length,
      critical: criticalIncidents.length,
      resolved: incidents.filter(i => i.status === "resolved").length,
    },
    casualties: {
      affected: totalAffected,
      displaced: totalDisplaced,
      injured: totalInjured,
      deceased: totalDeceased,
    },
    shelters: {
      total: shelters.length,
      open: openShelters.length,
      full: shelters.filter(s => s.status === "full").length,
      totalCapacity: totalShelterCap,
      totalOccupancy: totalShelterOcc,
      availableBeds: totalShelterCap - totalShelterOcc,
      loadPercent: Math.round((totalShelterOcc / totalShelterCap) * 100),
    },
    hospitals: {
      total: hospitals.length,
      critical: criticalHospitals.length,
      freeBeds: totalFreeBeds,
    },
    ambulances: {
      total: ambulanceTeams.length,
      active: activeAmbulances.length,
      available: ambulanceTeams.filter(a => a.status === "available").length,
    },
    generatedAt: new Date().toISOString(),
  };
}
